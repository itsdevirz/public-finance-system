      if ((item.account_kind?.includes("هزینه‌ای") || item.is_expense_form) && (item.row_type === "inventories" || item.has_inventories)) {
        errors.push({ code: 903, itemIndex: idx, itemRef, message: 'سطر موجودی‌ها در فرم‌های اعتبارات هزینه تکمیل نمی‌شود.' });
      }

      // ─── خطای ۹۰۴ (جدید) ──────────────────────────────────────────────────
      if ((item.row_type === "inventories" || item.is_inventory_row) && Number(item.inventory) > 0) {
        errors.push({ code: 904, itemIndex: idx, itemRef, message: 'در سطر موجودی‌ها، فیلد "موجودی‌ها" نمی‌تواند مقدار داشته باشد.' });
      }

      // ─── خطای ۹۰۶ (جدید) ──────────────────────────────────────────────────
      if (f9Transferred > 0 && !item.has_transfer_authorization && !item.is_university) {
        errors.push({ code: 906, itemIndex: idx, itemRef, message: 'دستگاه‌های اجرایی دارای مجوز انتقال (مانند دانشگاه‌ها) حسب مورد می‌توانند مبلغ فیلد "وجوه انتقالی" را تکمیل نمایند.' });
      }

      // ─── خطای ۹۰۷ (جدید) ──────────────────────────────────────────────────
      if (item.title) {
        const tStr = String(item.title).trim();
        if (form9Titles.has(tStr)) {
          errors.push({ code: 907, itemIndex: idx, itemRef, message: '"عنوان" (پیش‌پرداخت / علی‌الحساب / موجودی‌ها) نمی‌تواند تکراری انتخاب شود.' });
        } else {
          form9Titles.add(tStr);
        }
      }

      // ─── خطای ۹۰۸ (جدید) ──────────────────────────────────────────────────
      if (!item.title || !String(item.title).trim()) {
        errors.push({ code: 908, itemIndex: idx, itemRef, message: '"عنوان" تعیین نگردیده است.' });
      }
