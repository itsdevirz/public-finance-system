      errors.push({
        code: 48,
        itemIndex: idx,
        itemRef,
        message: 'شماره "ردیف متفرقه" تعیین شده در بخش ورود اطلاعات فرم‌های ۱ و ۲ نمی‌تواند با شماره "ردیف متفرقه" مندرج در بخش "تغییرات ناشی از استنادات قانونی" یکسان باشد.',
      });
